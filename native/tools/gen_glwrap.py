#!/usr/bin/env python3
"""Emit typed wrappers for OpenGL functions: `uint32_t gw_<name>(uint32_t *a)`.

Windows' opengl32 uses stdcall with every argument in 4-byte stack slots (8 for doubles and
64-bit ints). Each wrapper reads the guest's slots, converts pointers with G2H(), and calls the
host's GL through a pointer fetched by name, so the same code works whether guest memory is
the host's address space (native loader) or a separate 4 GiB region (recompiled build).

Functions whose arguments or result can't be expressed that way (pointer-to-pointer
arguments, pointer or floating-point results, callbacks) are left out; wglGetProcAddress then
reports them as unavailable. glGetString(i) is special-cased by opengl.c.
"""
import re
import sys

PROTO = re.compile(r"GLAPI\s+([\w\s\*]+?)\s*(?:GLAPIENTRY|APIENTRY)\s+(gl\w+)\s*\(([^;]*?)\)\s*;", re.S)
DOUBLE = {"GLdouble", "GLclampd"}
FLOAT = {"GLfloat", "GLclampf"}
INT64 = {"GLint64", "GLuint64", "GLint64EXT", "GLuint64EXT"}
INTPTR = {"GLintptr", "GLsizeiptr", "GLintptrARB", "GLsizeiptrARB", "GLvdpauSurfaceNV"}
OPAQUE_PTR = {"GLsync", "GLeglImageOES", "GLeglClientBufferEXT", "GLDEBUGPROC", "GLDEBUGPROCARB",
              "GLDEBUGPROCAMD", "GLDEBUGPROCKHR", "GLVULKANPROCNV", "GLhandleARB_ptr"}
SPECIAL = {"glGetString", "glGetStringi"}


def split_param(p):
    """('const GLfloat *', 'v') style: returns (type text, is_pointer)."""
    p = " ".join(p.split())
    p = re.sub(r"(\w+)\s*\[\s*\d*\s*\]", r"*\1", p)
    m = re.match(r"(.*?)(\w+)$", p)
    if m and m.group(1).strip() and not m.group(1).strip().endswith(("const", "unsigned", "signed")):
        typ = m.group(1).strip()
    else:
        typ = p
    return typ, "*" in typ


def base(typ):
    return [t for t in re.split(r"[\s\*]+", typ) if t and t != "const"][-1]


def wrapper(ret, name, params):
    ret = " ".join(ret.split())
    if ret != "void" and ("*" in ret or base(ret) in DOUBLE | FLOAT | INT64 | OPAQUE_PTR):
        return None
    params = " ".join(params.split())
    plist = [] if params in ("", "void") else [p.strip() for p in params.split(",")]
    decl, args = [], []
    slot = 0
    for p in plist:
        typ, ptr = split_param(p)
        if typ.count("*") > 1 or re.search(r"\*\s*const\s*\*", typ):
            return None
        b = base(typ)
        if b in OPAQUE_PTR:
            return None
        if ptr:
            decl.append(typ)
            args.append("(%s)gw_p(a[%d])" % (typ, slot))
            slot += 1
        elif b in DOUBLE:
            decl.append(typ)
            args.append("gw_f64(a + %d)" % slot)
            slot += 2
        elif b in INT64:
            decl.append(typ)
            args.append("(%s)gw_u64(a + %d)" % (typ, slot))
            slot += 2
        elif b in FLOAT:
            decl.append(typ)
            args.append("gw_f32(a[%d])" % slot)
            slot += 1
        elif b in INTPTR:
            decl.append(typ)
            args.append("(%s)(int32_t)a[%d]" % (typ, slot))
            slot += 1
        else:
            decl.append(typ)
            args.append("(%s)a[%d]" % (typ, slot))
            slot += 1
    proto = "%s (APIENTRY *)(%s)" % (ret, ", ".join(decl) or "void")
    call = "((%s)gw_ptr[GW_%s])(%s)" % (proto, name, ", ".join(args))
    body = ("%s; return 0;" % call) if ret == "void" else ("return (uint32_t)%s;" % call)
    return slot, "static uint32_t gw_%s(uint32_t *a) { (void)a; %s }" % (name, body)


def main():
    funcs = {}
    for path in sys.argv[1:]:
        with open(path, encoding="utf-8", errors="replace") as f:
            for ret, name, params in PROTO.findall(f.read()):
                if name in funcs or name in SPECIAL:
                    continue
                w = wrapper(ret, name, params)
                if w:
                    funcs[name] = w
    names = sorted(funcs)
    print("/* generated by tools/gen_glwrap.py from:", " ".join(sys.argv[1:]), "*/")
    print("enum {")
    for n in names:
        print("    GW_%s," % n)
    print("    GW_COUNT\n};")
    print("static void *gw_ptr[GW_COUNT];")
    print("static inline void *gw_p(uint32_t p) { return p ? G2H(void *, p) : NULL; }")
    print("static inline float gw_f32(uint32_t v) { float f; __builtin_memcpy(&f, &v, 4); return f; }")
    print("static inline double gw_f64(const uint32_t *a) { double d; __builtin_memcpy(&d, a, 8); return d; }")
    print("static inline uint64_t gw_u64(const uint32_t *a) { uint64_t v; __builtin_memcpy(&v, a, 8); return v; }")
    for n in names:
        print(funcs[n][1])
    print("static const struct gl_wrap { const char *name; unsigned short id, nargs; w32_fn fn; } gl_wraps[] = {")
    for n in names:
        print('    { "%s", GW_%s, %d, gw_%s },' % (n, n, funcs[n][0], n))
    print("};")


if __name__ == "__main__":
    main()
